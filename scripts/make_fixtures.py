def srgb_to_linear(c):
    c = np.maximum(c, 0.000061)
    return np.where(c > 0.04045, ((c * 0.947867 + 0.052133) ** 2.4), c * 0.0774)


def row_albedo64(row):
    """effective.row_albedo in float64 (same formulas, base roughness 0.5, no occlusion)."""
    row = row.astype(np.float64)
    base, dl = row[0], row[1]
    lut2, lut3, lut4, lut5, lut6 = row[2], row[3], row[4], row[5], row[6]
    cc = row[21]
    n = 512
    md0 = np.zeros(n)
    md1 = np.zeros(n)
    if base[3] <= 3.0:
        s = DETAIL[int(dl[0]) % 26].astype(np.float64) / 255.0 - 0.5
        md0, md1 = s[:, 2], s[:, 3]
    rough = np.clip(md0 * lut4[0] + md1 * lut4[1] + dl[3], 0, 1)
    inten = np.clip(md0 * lut3[0] + md1 * lut3[1] + dl[2], 0, 1)
    color = np.tile(base[:3], (n, 1))
    mix = np.ones(n)
    if cc[3] >= 0.0:
        c1, c2, c3, c4 = row[16], row[17], row[18], row[19]
        cs = np.clip((CAMO[int(cc[3]) % 5][:, :3].astype(np.float64) / 255.0 - 0.5) * cc[0] + cc[1], 0, 1)
        res = c1[None, :3] * (1 - cs[:, :1]) + c2[None, :3] * cs[:, :1]
        res = res * (1 - cs[:, 1:2]) + c3[None, :3] * cs[:, 1:2]
        res = res * (1 - cs[:, 2:3]) + c4[None, :3] * cs[:, 2:3]
        if base[3] != 1.0:
            mix = np.clip(md0 * c2[3] + md1 * c3[3] - row[20][3], 0, 1)
            color = res * (1 - mix[:, None]) + color * mix[:, None]
        else:
            color = res
    l2 = color + inten[:, None] * (lut2[None, :3] - color)
    cr = rough * mix
    l2 = l2 + cr[:, None] * (lut6[None, :3] - l2)
    cr2 = cr * rough
    l2 = l2 + cr2[:, None] * (lut5[None, :3] - l2)
    return srgb_to_linear(l2)


def row_info64(lut_hash, r):
    row = match.lut_data(lut_hash)[r]
    mean = row_albedo64(row).sum(0) / 512.0  # sequential sum would differ in the last bits only
    metallic = float(np.clip(float(row[6][3]), 0, 1))
    lab = effective.linear_to_lab(mean * (1 - 0.55 * metallic))
    return {'lab': lab, 'metal': metallic > 0.5, 'camo': bool(row[21][3] >= 0), 'mode': float(row[0][3])}


_ROW_INFO64 = {}


def row_info_cached(lut_hash, r):
    """row_info64, kept per row; a cape's tint rows (match.VIRTUAL_LUTS) are made again each time: three cape LUTs
    serve capes of different material LUTs."""
    if lut_hash in match.VIRTUAL_LUTS:
        return row_info64(lut_hash, r)
    return _ROW_INFO64.setdefault((lut_hash, r), row_info64(lut_hash, r))


# Coverage (float64, unrounded) ---------------------------------------------------------------------------------

def coverage64(s, archives, mask):
    for archive in archives:
        rec = s.toc(archive).get((int(mask, 16), TEX))
        if rec:
            break
    else:
        return None
    (om, sm), (os_, ss), (og, sg) = rec
    main = s.read_virtual(archive, om, sm)[0xC0:]
    h, w = np.frombuffer(main, '<u4', 2, 12)
    mips = int(np.frombuffer(main, '<u4', 1, 28)[0])
    fmt, _, _, layers = np.frombuffer(main, '<u4', 4, 128)
    if fmt not in (28, 29):
        return None
    per = sum(max(1, int(w) >> m) * max(1, int(h) >> m) * 4 for m in range(mips))
    total = per * int(layers)
    if sg >= total:
        data = s.read_virtual(archive + '.gpu_resources', og, sg)
    elif ss >= total:
        data = s.read_virtual(archive + '.stream', os_, ss)
    else:
        data = s.read_virtual(archive + '.stream', os_, ss) + s.read_virtual(archive + '.gpu_resources', og, sg)
    planes = [np.frombuffer(data, np.uint8, int(w) * int(h) * 4, layer * per).reshape(-1, 4).astype(np.float64) / 255.0
              for layer in range(int(layers))]
    stack = np.concatenate(planes, axis=1)
    tot = stack.sum(axis=1)
    valid = tot > 0.05
    weights = stack[valid] / tot[valid][:, None]
    return list(weights.sum(axis=0) / max(1, int(valid.sum())))


