def lua(value, indent=''):
    """A Lua literal for JSON-like data (dicts with string keys become tables)."""
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if value is None:
        return 'nil'
    if isinstance(value, (int, np.integer)):
        return str(int(value))
    if isinstance(value, (float, np.floating)):
        return repr(float(value))
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, (list, tuple)):
        return '{' + ', '.join(lua(v, indent) for v in value) + '}'
    if isinstance(value, dict):
        return '{' + ', '.join(f'{k} = {lua(v, indent)}' for k, v in value.items()) + '}'
    raise TypeError(type(value))


def write(name, body):
    FIXTURES.mkdir(parents=True, exist_ok=True)
    (FIXTURES / name).write_text('-- Generated by scripts/make_fixtures.py; do not edit.\nreturn ' + body + '\n',
                                 encoding='utf-8', newline='\n')


# Shared samples (float64) -------------------------------------------------------------------------------------

def detail_bytes():
    out = []
    for layer in range(26):
        a = shared_tex.bc7_layer('detail_tiler', layer, 4)  # float32 = uint8 / 255
        out.append(np.rint(a.reshape(-1, 4)[:512] * 255).astype(np.uint8))
    return out


def camo_bytes():
    out = []
    for layer in range(5):
        a = shared_tex.rgba8_layer('camo_tiler', layer, 2)
        out.append(np.rint(a.reshape(-1, 4)[:512] * 255).astype(np.uint8))
    return out


DETAIL = CAMO = None


def srgb_to_linear(c):
    c = np.maximum(c, 0.000061)
    return np.where(c > 0.04045, ((c * 0.947867 + 0.052133) ** 2.4), c * 0.0774)


def row_albedo64(row):
    """effective.row_albedo in float64 (same formulas, base roughness 0.5, no occlusion)."""
    row = row.astype(np.float64)
    base, dl = row[0], row[1]
    lut2, lut3, lut4, lut5, lut6 = row[2], row[3], row[4], row[5], row[6]
    cc = row[21]
    n = 512
    md0 = np.zeros(n)
    md1 = np.zeros(n)
    if base[3] <= 3.0:
        s = DETAIL[int(dl[0]) % 26].astype(np.float64) / 255.0 - 0.5
        md0, md1 = s[:, 2], s[:, 3]
    rough = np.clip(md0 * lut4[0] + md1 * lut4[1] + dl[3], 0, 1)
    inten = np.clip(md0 * lut3[0] + md1 * lut3[1] + dl[2], 0, 1)
    color = np.tile(base[:3], (n, 1))
    mix = np.ones(n)
    if cc[3] >= 0.0:
        c1, c2, c3, c4 = row[16], row[17], row[18], row[19]
        cs = np.clip((CAMO[int(cc[3]) % 5][:, :3].astype(np.float64) / 255.0 - 0.5) * cc[0] + cc[1], 0, 1)
        res = c1[None, :3] * (1 - cs[:, :1]) + c2[None, :3] * cs[:, :1]
        res = res * (1 - cs[:, 1:2]) + c3[None, :3] * cs[:, 1:2]
        res = res * (1 - cs[:, 2:3]) + c4[None, :3] * cs[:, 2:3]
        if base[3] != 1.0:
            mix = np.clip(md0 * c2[3] + md1 * c3[3] - row[20][3], 0, 1)
            color = res * (1 - mix[:, None]) + color * mix[:, None]
        else:
            color = res
    l2 = color + inten[:, None] * (lut2[None, :3] - color)
    cr = rough * mix
    l2 = l2 + cr[:, None] * (lut6[None, :3] - l2)
    cr2 = cr * rough
    l2 = l2 + cr2[:, None] * (lut5[None, :3] - l2)
    return srgb_to_linear(l2)


def row_info64(lut_hash, r):
    row = match.lut_data(lut_hash)[r]
    mean = row_albedo64(row).sum(0) / 512.0  # sequential sum would differ in the last bits only
    metallic = float(np.clip(float(row[6][3]), 0, 1))
    lab = effective.linear_to_lab(mean * (1 - 0.55 * metallic))
    return {'lab': lab, 'metal': metallic > 0.5, 'camo': bool(row[21][3] >= 0), 'mode': float(row[0][3])}


# Coverage (float64, unrounded) ---------------------------------------------------------------------------------

def coverage64(s, archives, mask):
    for archive in archives:
        rec = s.toc(archive).get((int(mask, 16), TEX))
        if rec:
            break
    else:
        return None
    (om, sm), (os_, ss), (og, sg) = rec
    main = s.read_virtual(archive, om, sm)[0xC0:]
    h, w = np.frombuffer(main, '<u4', 2, 12)
    mips = int(np.frombuffer(main, '<u4', 1, 28)[0])
    fmt, _, _, layers = np.frombuffer(main, '<u4', 4, 128)
    if fmt not in (28, 29):
        return None
    per = sum(max(1, int(w) >> m) * max(1, int(h) >> m) * 4 for m in range(mips))
    total = per * int(layers)
    if sg >= total:
        data = s.read_virtual(archive + '.gpu_resources', og, sg)
    elif ss >= total:
        data = s.read_virtual(archive + '.stream', os_, ss)
    else:
        data = s.read_virtual(archive + '.stream', os_, ss) + s.read_virtual(archive + '.gpu_resources', og, sg)
    planes = [np.frombuffer(data, np.uint8, int(w) * int(h) * 4, layer * per).reshape(-1, 4).astype(np.float64) / 255.0
              for layer in range(int(layers))]
    stack = np.concatenate(planes, axis=1)
    tot = stack.sum(axis=1)
    valid = tot > 0.05
    weights = stack[valid] / tot[valid][:, None]
    return list(weights.sum(axis=0) / max(1, int(valid.sum())))


TRANSFER_EVERY = 150
TEST_PAIR = {'a5574ac2', '0ade6719'}  # tests/test_job.lua: CPR-80 Bulwark helmet, DS-191 Scorpion armor


def transfer_cases(mapping, target):
    """[{key, L, a, b, colors (8 x RGB), err, cal}] for every planned row, in key order."""
    out = []
    cal = {r['key']: r['cal'] for r in target.rows}
    for tk, (_, _, desired) in sorted(mapping.items(), key=lambda kv: f'{kv[0][0]}:{kv[0][1]}'):
        row, _, err = match12.recolor_row(match.lut_data(tk[0])[tk[1]], desired, tk, cal[tk])
        colors = [float(row[c][ch]) for c in match11.COLOUR_COLUMNS for ch in range(3)]
        out.append({'key': f'{tk[0]}:{tk[1]}', 'L': float(desired[0]), 'a': float(desired[1]), 'b': float(desired[2]),
                    'colors': colors, 'err': float(err), 'cal': bool(cal[tk])})
    return out


def main():
    global DETAIL, CAMO
    limit = int(sys.argv[sys.argv.index('--limit') + 1]) if '--limit' in sys.argv else None
    t0 = time.time()
    DETAIL, CAMO = detail_bytes(), camo_bytes()
    write('shared.lua', lua({'detail': [bytes(d.reshape(-1)).hex() for d in DETAIL],
                             'camo': [bytes(c.reshape(-1)).hex() for c in CAMO]}))
    s = slim.Slim()
    kits = [k for k in json.load(open(RESEARCH / 'dataset.json', encoding='utf-8')) if k['kit_type'] in ('Helmet', 'Armor')]
    scoped = eval_scope.scoped(kits, s)
    # float64 coverage for every mask in scope
    cache = {}
    for k in scoped:
        archives = [k['archive'], eval_scope.SHARED]
        for p in k['pieces']:
            for m in p['materials']:
                mask = m.get('id_masks')
                if mask and m.get('coverage') is not None:
                    if mask not in cache:
                        cache[mask] = coverage64(s, archives, mask)
                    m['coverage'] = cache[mask]
    print('coverage', round(time.time() - t0, 1), 's', len(cache), 'masks')
    match.row_info = lambda lut_hash, r, _c={}: _c.setdefault((lut_hash, r), row_info64(lut_hash, r))
    items = {k['id']: match12.Item(k) for k in scoped}
    print('measured items', sum(1 for i in items.values() if i.measured), 'of', len(items))
    print('items', round(time.time() - t0, 1), 's')
    # catalogue fixture (the scoped pieces are the runtime's too, but the Lua side gets the full piece list)
    catalogue = []
    for k in kits:
        catalogue.append({'id': k['id'], 'archive': k['archive'], 'kit_type': k['kit_type'], 'set_id': k['set_id'],
                          'name': k['name'] or k['id'],
                          'pieces': [{'path': p['path'], 'slot': SLOTS.index(p['slot']), 'type': TYPES.index(p['type']),
                                      'body': BODIES.index(p['body']), 'lut': p['lut_override'],
                                      'pattern': p['pattern_lut'], 'tone': p['tone_variations']}
                                     for p in k['pieces']]})
    write('kits.lua', lua(catalogue))
    rows = {}
    for kid, item in items.items():
        rows[kid] = [[r['key'][0] + ':' + str(r['key'][1]), r['tex_area'], r['tex_under'], float(r['model_lab'][0]),
                      float(r['model_lab'][1]), float(r['model_lab'][2]), r['metal'], r['camo'], r['mode'],
                      match11.full_metal(r['key'])]
                     + [float(x) for x in match12.mean_albedo(match.lut_data(r['key'][0])[r['key'][1]])]
                     for r in item.rows]
    write('rows.lua', '{' + ', '.join(f'["{k}"] = {lua(v)}' for k, v in rows.items()) + '}')
    pats = {kid: [[pt['pattern'], pt['tex_area']] for pt in match12.item_patterns(item)] for kid, item in items.items()}
    write('patterns.lua', '{' + ', '.join(f'["{k}"] = {lua(v)}' for k, v in pats.items() if v) + '}')
    helmets = [k['id'] for k in kits if k['kit_type'] == 'Helmet'][:limit]
    armors = [k['id'] for k in kits if k['kit_type'] == 'Armor'][:limit]
    plans, transfers, pattern_plans, index = {}, {}, {}, 0
    for h in helmets:
        for a in armors:
            for direction, t, src in (('h', h, a), ('a', a, h)):
                mapping = match12.plan(items[t], items[src])
                parts = []
                for tk, (kind, g, _) in sorted(mapping.items(), key=lambda kv: f'{kv[0][0]}:{kv[0][1]}'):
                    rep = g['rep']['key']
                    parts.append(f'{tk[0]}:{tk[1]}=' + ('~' if kind == 'accent' else '') + f'{rep[0]}:{rep[1]}')
                text = ';'.join(parts)
                key = f'{direction}{t}{src}'
                plans[key] = zlib.adler32(text.encode())
                pplan = match12.plan_patterns(items[t], items[src])
                if pplan:
                    ptext = ';'.join(f'{h}={acc["rep"]["key"][0]}:{acc["rep"]["key"][1]}'
                                     for h, (acc, _) in sorted(pplan.items()))
                    pattern_plans[key] = zlib.adler32(ptext.encode())
                if index % TRANSFER_EVERY == 0 or {t, src} == TEST_PAIR:
                    transfers[key] = transfer_cases(mapping, items[t])
                index += 1
    write('plans.lua', '{' + ', '.join(f'{k} = {v}' for k, v in plans.items()) + '}')
    write('transfers.lua', '{' + ', '.join(f'{k} = {lua(v)}' for k, v in transfers.items()) + '}')
    write('pattern_plans.lua', '{' + ', '.join(f'{k} = {v}' for k, v in pattern_plans.items()) + '}')
    print('pattern plans', len(pattern_plans))
    print('transfers', len(transfers), 'plans,', sum(len(v) for v in transfers.values()), 'rows')
    print('plans', len(plans), round(time.time() - t0, 1), 's')
    if '--quality' in sys.argv:
        results = []
        for h in helmets:
            for a in armors:
                for direction, t, src in (('helmet<-armor', h, a), ('armor<-helmet', a, h)):
                    mapping, _ = match.plan(items[t], items[src], 'full')
                    m = match.metrics(items[t], items[src], mapping, 'full')
                    m.update({'direction': direction, 'same_set': items[h].kit['set_id'] == items[a].kit['set_id']})
                    results.append(m)
        summary = match.summarize(results)
        for d, v in summary.items():
            print(d, {k: (round(x, 4) if isinstance(x, float) else x) for k, x in v.items() if k in (
                'pairs', 'worse', 'lens_untouched', 'foreign_before_median', 'foreign_after_median',
                'foreign_after_p99', 'foreign_after_max', 'light_lost')})


if __name__ == '__main__':
    main()
